"""Makes ``python -m cartographer`` work.

What this module does
---------------------
When you run ``python -m cartographer ...``, Python finds the *package* ``cartographer``, then
looks for a module called ``__main__`` inside it and runs that module as the main program. This
file hands control to :func:`cartographer.cli.main.main` and turns its integer result into the
process's exit code.

Why it exists
-------------
Three ways of starting Cartographer must behave the same (spec M0 §5.1): the ``cartographer``
command, the ``carto`` alias, and ``python -m cartographer``. The first two are console-script
entry points generated by the installer (``[project.scripts]`` in ``pyproject.toml``). This
file covers the third. ``python -m`` is useful when the scripts directory isn't on your
``PATH``, or when you want a *specific* interpreter: ``py -3.13 -m cartographer``.

Python concepts used here
-------------------------
- ``python -m`` and ``__main__`` (docs/learn/concepts/how-python-runs-code.md).
- ``SystemExit`` (docs/learn/concepts/how-python-runs-code.md): raising it ends the program
  with the given exit code. That's what ``sys.exit(code)`` does under the hood.

How to read this file
---------------------
Two lines of code. ``main()`` never calls ``sys.exit`` itself (that keeps it testable, D-054),
so the exit happens here.
"""

from cartographer.cli.main import main

# CONCEPT(how-python-runs-code): `raise SystemExit(n)` is exactly what `sys.exit(n)` does. The
# interpreter catches it at the top level and uses `n` as the process exit code.
raise SystemExit(main())
